package dev.gamepadtweaks;

import java.lang.foreign.Arena;
import java.lang.foreign.FunctionDescriptor;
import java.lang.foreign.Linker;
import java.lang.foreign.MemoryLayout;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.SymbolLookup;
import java.lang.foreign.ValueLayout;
import java.lang.invoke.MethodHandle;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import se.krka.kahlua.integration.annotations.LuaMethod;
import zombie.GameWindow;
import zombie.core.znet.SteamUtils;
import zombie.gameStates.ChooseGameInfo;
import org.lwjglx.input.Controller;

// Mod actions as Steam Input game actions.
//
// Vanilla doesn't use the Steam Input API: Steam only emulates a gamepad for it, so a
// Steam configuration can put gamepad buttons, keys and mouse on the controller, but not
// the mod's actions (horn, lights, drop items...), and the extra buttons (back paddles)
// or Steam activators (long press, double press, chords) can't reach them.
// Here the game registers an action manifest (media/steam_input/manifest.vdf, generated by
// tools/steam_input.py) through ISteamInput::SetInputActionManifestFilePath, so the actions
// show up in the Steam configurator as "game actions". Its default configurations are Steam's
// "Gamepad" templates, so sticks and buttons still go to the emulated gamepad.
// libsteam_api is already loaded by the game (ZNetJNI); it's called through the flat C API
// with the Foreign Function API. The Lua side (Bindings.lua) polls the events every frame.
public final class SteamInput {
    private static final long ALL_CONTROLLERS = -1L; // STEAM_INPUT_HANDLE_ALL_CONTROLLERS
    private static final int MAX_CONTROLLERS = 16;   // STEAM_INPUT_MAX_COUNT
    private static final String ACTION_SET = "game";
    private static final long HANDLE_RETRY_MS = 2000;
    private static final Pattern BUTTON_ACTION = Pattern.compile("\"(\\w+)\"\\s+\"#act_\\w+\"");

    private static boolean tried;
    private static boolean ready;
    private static MemorySegment input;
    private static MethodHandle runFrame, getConnectedControllers, getActionSetHandle, activateActionSet,
            getDigitalActionHandle, getDigitalActionData, getGamepadIndexForController, getInputTypeForHandle;

    private static final List<String> actionNames = new ArrayList<>();
    private static long[] actionHandles;
    private static long actionSet;
    private static long lastHandleTry;
    private static MemorySegment handleBuffer;
    private static final Arena arena = Arena.global();
    private static java.lang.foreign.SegmentAllocator dataAllocator;
    // controller handle -> [action] = held
    private static final Map<Long, boolean[]> held = new HashMap<>();
    private static final Map<Long, Integer> loggedMapping = new HashMap<>();
    private static final long MAPPING_REFRESH_MS = 2000;
    // controller handle -> game controller id, refreshed every MAPPING_REFRESH_MS
    private static final Map<Long, Integer> mapping = new HashMap<>();
    private static long mappingTime;
    // layers wanted by Lua: game controller id -> "a,b" (bottom to top); -1: for any other
    private static final Map<Integer, String> wantedLayers = new HashMap<>();
    private static String defaultLayers = "";
    // controller handle -> layers active on it
    private static final Map<Long, String> activeLayers = new HashMap<>();
    private static final Map<String, Long> layerHandles = new HashMap<>();
    private static MethodHandle activateActionSetLayer, deactivateAllActionSetLayers;

    private SteamInput() {}

    /** Registers the action manifest once (Steam must be running, steamInput.enabled=true). */
    @LuaMethod(name = "GamepadTweaks_steamInputInit", global = true)
    public static boolean init() {
        if (tried) {
            return ready;
        }
        Settings.refresh();
        if (!Settings.steamInput) {
            return false;
        }
        if (!SteamUtils.isSteamModeEnabled()) {
            return false; // not yet / non-Steam build; retried on the next call
        }
        tried = true;
        try {
            Path manifest = manifestPath();
            if (manifest == null || !Files.isRegularFile(manifest)) {
                Log.warn("steam input: manifest not found: " + manifest);
                return false;
            }
            readActionNames(manifest);
            bind();
            MethodHandle setManifest = handle("SteamAPI_ISteamInput_SetInputActionManifestFilePath",
                    FunctionDescriptor.of(ValueLayout.JAVA_BOOLEAN, ValueLayout.ADDRESS, ValueLayout.ADDRESS));
            MethodHandle initFn = handle("SteamAPI_ISteamInput_Init",
                    FunctionDescriptor.of(ValueLayout.JAVA_BOOLEAN, ValueLayout.ADDRESS, ValueLayout.JAVA_BOOLEAN));
            // false: SteamAPI_RunCallbacks (called by the game every frame) runs the frames too
            boolean inited = (boolean) initFn.invokeExact(input, false);
            boolean loaded = (boolean) setManifest.invokeExact(input, arena.allocateFrom(manifest.toString()));
            Log.info("steam input: init=" + inited + ", manifest " + manifest + " loaded=" + loaded
                    + ", " + actionNames.size() + " actions");
            ready = inited;
            dataAllocator = java.lang.foreign.SegmentAllocator.prefixAllocator(arena.allocate(16));
            handleBuffer = arena.allocate(ValueLayout.JAVA_LONG, MAX_CONTROLLERS);
            actionHandles = new long[actionNames.size()];
        } catch (Throwable t) {
            Log.error("steam input init failed", t);
        }
        return ready;
    }

    /**
     * Returns the action presses and releases since the last call as
     * "action:controllerId:1;action:controllerId:0;..." (controllerId = JoypadState.controllers
     * index, -1 = unknown), or nil.
     */
    @LuaMethod(name = "GamepadTweaks_steamInputPoll", global = true)
    public static String poll() {
        if (!init()) {
            return null;
        }
        try {
            return pollEvents();
        } catch (Throwable t) {
            Log.error("steam input poll failed", t);
            ready = false;
            return null;
        }
    }

    private static String pollEvents() throws Throwable {
        runFrame.invokeExact(input, false);
        if (!resolveHandles()) {
            return null;
        }
        int count = (int) getConnectedControllers.invokeExact(input, handleBuffer);
        StringBuilder events = null;
        Map<Long, boolean[]> seen = new HashMap<>();
        long now = System.currentTimeMillis();
        if (now - mappingTime > MAPPING_REFRESH_MS) {
            mappingTime = now;
            mapping.clear();
        }
        for (int i = 0; i < Math.min(count, MAX_CONTROLLERS); i++) {
            long controller = handleBuffer.getAtIndex(ValueLayout.JAVA_LONG, i);
            activateActionSet.invokeExact(input, controller, actionSet);
            boolean[] prev = held.computeIfAbsent(controller, k -> new boolean[actionNames.size()]);
            seen.put(controller, prev);
            Integer mapped = mapping.get(controller);
            if (mapped == null) {
                mapped = controllerId(controller);
                mapping.put(controller, mapped);
            }
            int id = mapped;
            applyLayers(controller, id);
            for (int a = 0; a < actionHandles.length; a++) {
                if (actionHandles[a] == 0) {
                    continue;
                }
                MemorySegment data = (MemorySegment) getDigitalActionData.invokeExact(
                        dataAllocator, input, controller, actionHandles[a]);
                boolean state = data.get(ValueLayout.JAVA_BOOLEAN, 0) && data.get(ValueLayout.JAVA_BOOLEAN, 1);
                if (state == prev[a]) {
                    continue;
                }
                prev[a] = state;
                if (Settings.steamInputDebugLog) {
                    Log.info("steam input: " + actionNames.get(a) + (state ? " down" : " up")
                            + " handle=" + Long.toUnsignedString(controller) + " -> controller " + id);
                }
                events = append(events, actionNames.get(a), id, state);
            }
        }
        // disconnected controllers: nothing to release on the Lua side (the joypad is gone too)
        held.keySet().retainAll(seen.keySet());
        activeLayers.keySet().retainAll(seen.keySet());
        return events == null ? null : events.toString();
    }

    /**
     * Layers to activate, from the player's situation (Bindings.lua): "id=a,b;id=c;*=d",
     * id = JoypadState.controllers index, * = any other controller; names bottom to top.
     */
    @LuaMethod(name = "GamepadTweaks_steamInputSetLayers", global = true)
    public static void setLayers(String spec) {
        wantedLayers.clear();
        defaultLayers = "";
        if (spec == null) {
            return;
        }
        for (String part : spec.split(";")) {
            int eq = part.indexOf('=');
            if (eq <= 0) {
                continue;
            }
            String key = part.substring(0, eq).trim();
            String layers = part.substring(eq + 1).trim();
            if (key.equals("*")) {
                defaultLayers = layers;
            } else {
                try {
                    wantedLayers.put(Integer.parseInt(key), layers);
                } catch (NumberFormatException e) {
                    Log.warn("steam input: bad layer spec " + part);
                }
            }
        }
    }

    // An unmapped controller (-1) gets the only player's layers, as in Bindings.lua.
    private static String layersFor(int id) {
        String layers = wantedLayers.get(id);
        if (layers == null && id < 0 && wantedLayers.size() == 1) {
            layers = wantedLayers.values().iterator().next();
        }
        return layers != null ? layers : defaultLayers;
    }

    private static void applyLayers(long controller, int id) throws Throwable {
        String layers = layersFor(id);
        if (layers.equals(activeLayers.get(controller))) {
            return;
        }
        deactivateAllActionSetLayers.invokeExact(input, controller);
        for (String name : layers.split(",")) {
            if (name.isEmpty()) {
                continue;
            }
            Long h = layerHandles.get(name);
            if (h == null || h == 0) {
                h = (long) getActionSetHandle.invokeExact(input, arena.allocateFrom(name));
                layerHandles.put(name, h);
            }
            if (h != 0) {
                activateActionSetLayer.invokeExact(input, controller, (long) h);
            }
        }
        activeLayers.put(controller, layers);
        if (Settings.steamInputDebugLog) {
            Log.info("steam input: layers [" + layers + "] on " + Long.toUnsignedString(controller) + " (controller " + id + ")");
        }
    }

    private static StringBuilder append(StringBuilder sb, String action, int id, boolean down) {
        if (sb == null) {
            sb = new StringBuilder();
        } else {
            sb.append(';');
        }
        return sb.append(action).append(':').append(id).append(':').append(down ? '1' : '0');
    }

    // Action handles are 0 until Steam has parsed the manifest; retried every few seconds.
    private static boolean resolveHandles() throws Throwable {
        long now = System.currentTimeMillis();
        boolean missing = actionSet == 0;
        for (long h : actionHandles) {
            missing |= h == 0;
        }
        if (!missing || now - lastHandleTry < HANDLE_RETRY_MS) {
            return actionSet != 0;
        }
        lastHandleTry = now;
        actionSet = (long) getActionSetHandle.invokeExact(input, arena.allocateFrom(ACTION_SET));
        int found = 0;
        for (int a = 0; a < actionHandles.length; a++) {
            if (actionHandles[a] == 0) {
                actionHandles[a] = (long) getDigitalActionHandle.invokeExact(input, arena.allocateFrom(actionNames.get(a)));
            }
            if (actionHandles[a] != 0) {
                found++;
            }
        }
        Log.info("steam input: action set " + (actionSet != 0 ? "found" : "not found yet")
                + ", " + found + "/" + actionHandles.length + " action handles");
        return actionSet != 0;
    }

    // Steam controller -> the game's controller (JoypadState.controllers index), or -1.
    // Steam reports which emulated gamepad belongs to a controller (GetGamepadIndexForController);
    // the game sees those as "... pad N" joysticks. -1: Lua picks the only player's joypad.
    private static int controllerId(long controller) throws Throwable {
        int pad = (int) getGamepadIndexForController.invokeExact(input, controller);
        int result = -1;
        String how = "none";
        int controllers = GameWindow.GameInput.getControllerCount();
        if (pad >= 0) {
            for (int i = 0; i < controllers; i++) {
                Controller c = GameWindow.GameInput.getController(i);
                String name = c == null ? null : c.getJoystickName();
                if (name != null && name.endsWith(" pad " + pad)) {
                    result = i;
                    how = "name '" + name + "'";
                    break;
                }
            }
        }
        Integer prev = loggedMapping.put(controller, result);
        if (prev == null || prev != result) {
            int type = (int) getInputTypeForHandle.invokeExact(input, controller);
            StringBuilder names = new StringBuilder();
            for (int i = 0; i < controllers; i++) {
                Controller c = GameWindow.GameInput.getController(i);
                names.append(i).append('=').append(c == null ? "-" : c.getJoystickName()).append(", ");
            }
            Log.info("steam input: controller " + Long.toUnsignedString(controller) + " (type " + type
                    + ", gamepad index " + pad + ") -> " + result + " by " + how + "; game controllers: " + names);
        }
        return result;
    }

    private static Path manifestPath() {
        ChooseGameInfo.Mod mod = ChooseGameInfo.getModDetails("GamepadTweaks");
        if (mod == null || mod.getVersionDir() == null) {
            return null;
        }
        return Path.of(mod.getVersionDir(), "media", "steam_input", "manifest.vdf").toAbsolutePath();
    }

    // Button actions of the set and its layers, in manifest order.
    private static void readActionNames(Path manifest) throws java.io.IOException {
        String text = Files.readString(manifest, StandardCharsets.UTF_8);
        Matcher m = BUTTON_ACTION.matcher(text);
        while (m.find()) {
            if (!actionNames.contains(m.group(1))) {
                actionNames.add(m.group(1));
            }
        }
    }

    private static SymbolLookup lookup;

    private static void bind() throws Throwable {
        lookup = steamApi();
        MethodHandle accessor = handle("SteamAPI_SteamInput_v006", FunctionDescriptor.of(ValueLayout.ADDRESS));
        input = (MemorySegment) accessor.invokeExact();
        if (input.address() == 0) {
            throw new IllegalStateException("SteamInput() is null");
        }
        runFrame = handle("SteamAPI_ISteamInput_RunFrame",
                FunctionDescriptor.ofVoid(ValueLayout.ADDRESS, ValueLayout.JAVA_BOOLEAN));
        getConnectedControllers = handle("SteamAPI_ISteamInput_GetConnectedControllers",
                FunctionDescriptor.of(ValueLayout.JAVA_INT, ValueLayout.ADDRESS, ValueLayout.ADDRESS));
        getActionSetHandle = handle("SteamAPI_ISteamInput_GetActionSetHandle",
                FunctionDescriptor.of(ValueLayout.JAVA_LONG, ValueLayout.ADDRESS, ValueLayout.ADDRESS));
        activateActionSet = handle("SteamAPI_ISteamInput_ActivateActionSet",
                FunctionDescriptor.ofVoid(ValueLayout.ADDRESS, ValueLayout.JAVA_LONG, ValueLayout.JAVA_LONG));
        activateActionSetLayer = handle("SteamAPI_ISteamInput_ActivateActionSetLayer",
                FunctionDescriptor.ofVoid(ValueLayout.ADDRESS, ValueLayout.JAVA_LONG, ValueLayout.JAVA_LONG));
        deactivateAllActionSetLayers = handle("SteamAPI_ISteamInput_DeactivateAllActionSetLayers",
                FunctionDescriptor.ofVoid(ValueLayout.ADDRESS, ValueLayout.JAVA_LONG));
        getDigitalActionHandle = handle("SteamAPI_ISteamInput_GetDigitalActionHandle",
                FunctionDescriptor.of(ValueLayout.JAVA_LONG, ValueLayout.ADDRESS, ValueLayout.ADDRESS));
        // InputDigitalActionData_t { bool bState; bool bActive; }, returned by value
        getDigitalActionData = handle("SteamAPI_ISteamInput_GetDigitalActionData",
                FunctionDescriptor.of(MemoryLayout.structLayout(ValueLayout.JAVA_BOOLEAN, ValueLayout.JAVA_BOOLEAN),
                        ValueLayout.ADDRESS, ValueLayout.JAVA_LONG, ValueLayout.JAVA_LONG));
        getGamepadIndexForController = handle("SteamAPI_ISteamInput_GetGamepadIndexForController",
                FunctionDescriptor.of(ValueLayout.JAVA_INT, ValueLayout.ADDRESS, ValueLayout.JAVA_LONG));
        getInputTypeForHandle = handle("SteamAPI_ISteamInput_GetInputTypeForHandle",
                FunctionDescriptor.of(ValueLayout.JAVA_INT, ValueLayout.ADDRESS, ValueLayout.JAVA_LONG));
    }

    private static MethodHandle handle(String name, FunctionDescriptor fd) {
        MemorySegment fn = lookup.find(name).orElseThrow(() -> new IllegalStateException(name + " not found"));
        return Linker.nativeLinker().downcallHandle(fn, fd);
    }

    // The game's own copy (already loaded, so dlopen/LoadLibrary returns the same instance).
    private static SymbolLookup steamApi() {
        String[] names = {System.mapLibraryName("steam_api64"), System.mapLibraryName("steam_api")};
        String paths = System.getProperty("java.library.path", "");
        for (String dir : paths.split(java.io.File.pathSeparator)) {
            for (String name : names) {
                Path p = Path.of(dir.isEmpty() ? "." : dir, name);
                if (Files.isRegularFile(p)) {
                    return SymbolLookup.libraryLookup(p.toAbsolutePath(), Arena.global());
                }
            }
        }
        return SymbolLookup.libraryLookup(names[1], Arena.global());
    }
}

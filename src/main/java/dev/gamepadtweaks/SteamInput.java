    private static MethodHandle handle(String name, FunctionDescriptor fd) {
        MemorySegment fn = lookup.find(name).orElseThrow(() -> new IllegalStateException(name + " not found"));
        return Linker.nativeLinker().downcallHandle(fn, fd);
    }

    // The game's own copy (already loaded, so dlopen/LoadLibrary returns the same instance).
    private static SymbolLookup steamApi() {
        String[] names = {System.mapLibraryName("steam_api64"), System.mapLibraryName("steam_api")};
        String paths = System.getProperty("java.library.path", "");
        for (String dir : paths.split(java.io.File.pathSeparator)) {
            for (String name : names) {
                Path p = Path.of(dir.isEmpty() ? "." : dir, name);
                if (Files.isRegularFile(p)) {
                    return SymbolLookup.libraryLookup(p.toAbsolutePath(), Arena.global());
                }
            }
        }
        return SymbolLookup.libraryLookup(names[1], Arena.global());
    }
